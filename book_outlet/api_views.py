from drf_spectacular.utils import OpenApiParameter, extend_schema, extend_schema_view
from rest_framework import filters, viewsets
from rest_framework.authtoken.views import ObtainAuthToken

from .models import Author, Book
from .serializers import AuthorSerializer, BookSerializer, LoginSerializer, TokenSerializer


# DRF's login view, unchanged, plus a description for the docs page. Without it the generated
# docs wrongly demand a "token" in the login request, which blocks "Try it out".
# auth=[] says the login itself needs no token.
class LoginView(ObtainAuthToken):
    @extend_schema(request=LoginSerializer, responses=TokenSerializer, auth=[])
    def post(self, request, *args, **kwargs):
        return super().post(request, *args, **kwargs)


# The docs are generated by reading the code. ?search= is declared by the filter backend, so it
# shows up on its own; ?bestselling= is read by hand in get_queryset(), so we describe it here.
@extend_schema_view(
    list=extend_schema(parameters=[
        OpenApiParameter("bestselling", bool, description="true = only bestsellers"),
    ]),
)
class BookViewSet(viewsets.ModelViewSet):
    # select_related fetches each book's author in the same query instead of one query per book;
    # prefetch_related does the same job for the many countries, in one extra query
    queryset = (Book.objects.select_related("author")
                .prefetch_related("published_countries")
                .order_by("-rating", "title"))
    serializer_class = BookSerializer

    # ?search=hobbit looks in these fields; ?ordering=title (or -title) sorts by these fields.
    # Without ?ordering= the order set on the queryset above is kept.
    filter_backends = [filters.SearchFilter, filters.OrderingFilter]
    search_fields = ["title", "author__first_name", "author__last_name"]
    ordering_fields = ["title", "rating"]

    def get_queryset(self):
        queryset = super().get_queryset()
        # ?bestselling=true keeps only bestsellers
        if self.request.query_params.get("bestselling") == "true":
            queryset = queryset.filter(is_bestselling=True)
        return queryset


class AuthorViewSet(viewsets.ModelViewSet):
    queryset = Author.objects.order_by("last_name", "first_name")
    serializer_class = AuthorSerializer
